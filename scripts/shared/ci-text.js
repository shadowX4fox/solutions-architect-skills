// bodies, issue and pull request comments, commit statuses, commit messages, job summary headings. The workflows' own
// sentences live here; a script's reasons live beside their logic, each an { en, es } pair picked with `pick`.
// Logs (::error::, echo) and the tools' receipts quoted in a comment stay as the tools print them.
//
//   bun ci-text.js <key> [--project <dir>] [--lang <xx>] [name=value …]     prints the message, {name} filled
//   bun ci-text.js --lang-of <dir>                                           prints the language: en | es
//   bun ci-text.js --codec <mood> [<key>] [--project <dir>] [name=value …]   prints Alia's codec heading, the key's message beside it
//
// The language: --lang → DOC_LANGUAGE in <dir>/ARCHITECTURE.md (the legacy LANGUAGE marker read too) → SA_DOC_LANGUAGE
// (a service repository's variable, set by ci-setup.js --settings) → en. Anything but en / es is en.
'use strict';
const fs = require('fs');
const path = require('path');

const LANGS = ['en', 'es'];
const norm = (l) => (LANGS.includes(String(l || '').toLowerCase()) ? String(l).toLowerCase() : null);

function languageOf(dir, env = process.env) {
  if (dir) {
    try {
      const head = fs.readFileSync(path.join(dir, 'ARCHITECTURE.md'), 'utf8').replace(/\r\n?/g, '\n').split('\n').slice(0, 60).join('\n');
      const m = head.match(/<!--\s*(?:DOC_LANGUAGE|LANGUAGE):\s*([a-zA-Z]{2})\s*-->/);
      if (m && norm(m[1])) return norm(m[1]);
    } catch (e) { /* no architecture here: a service repository */ }
  }
  return norm(env.SA_DOC_LANGUAGE) || 'en';
}

const fill = (s, vars = {}) => String(s).replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? m : String(vars[k])));
// one message in the language: an { en, es } pair, English when the language has none
const pick = (lang, pair, vars) => fill(pair[norm(lang) || 'en'] ?? pair.en, vars);

