#!/usr/bin/env bun
// kit-gaps-merge.js — the asset gaps of a component, merged into its Component Specification § 11.
//
//   bun kit-gaps-merge.js <handoffs/components/NN-slug.md> <asset-gaps.json> [--dry-run] [--json]
//   asset-gaps.json: { "gaps": [{ asset, field, where, impact }], "assets": ["<file>", …] }   (`assets` optional)
//
// § 11 Open questions is a four-column register (Section · What is missing · Where to fix it · What it
// blocks). The asset generators report their gaps in ASSET_RESULT.gaps[]; the orchestrator writes them
// once as { "gaps": [{ asset, field, where, impact }] } and this script appends one row per gap under
// `Section = Assets — <asset filename>`. When § 11 still carries the "No gaps detected" line the table is
// created in its place. A row already present is not added twice, so re-running is safe.
//
// An asset's rows are replaced, not accumulated (8.112.0): the gaps file is the regenerated assets' whole register, so a
// row under `Assets — <file>` for an asset it names (`gaps[].asset`, or `assets: [...]` for an asset regenerated with no
// gap left) and that it no longer carries is removed. Through 8.111.0 a regenerated `openapi.yaml` added its five new
// gaps beside the six of the run before, two of them closed. Rows of other assets and the specification's own rows stay.
//
// Through 8.27.0 Step 5.3 asked the orchestrator to anchor on `[OPEN_QUESTIONS_LIST …]` and on a
// `**Format for each gap:**` line — neither existed once § 11 became a table — and the merge silently
// never happened. A deterministic step that can drift from its template is a step for a script.
'use strict';
const fs = require('fs');

const ANCHOR = /^(#{2,4})\s+(.+?)\s*<!--\s*SECTION:\s*Open Questions\s*-->\s*$/m;
const HEADER = '| Section | What is missing | Where to fix it | What it blocks |';
const SEP = '|---------|-----------------|-----------------|----------------|';
const NOGAPS = /^No gaps detected — all sections fully documented\.?$|^No se detectaron vac[ií]os[^\n]*$/im;
const cell = (s) => String(s == null ? '' : s).replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|').trim();
const row = (g) => `| Assets — ${cell(g.asset)} | ${cell(g.field)} | ${cell(g.where)} | ${cell(g.impact)} |`;

const assetOf = (line) => { const m = line.match(/^\|\s*Assets — (.+?)\s*\|/); return m ? m[1].replace(/\\\|/g, '|') : null; };

function merge(src, gaps, opts = {}) {
  const m = src.match(ANCHOR);
  if (!m) return { error: 'no `<!-- SECTION: Open Questions -->` heading — the Component Specification failed validation; log for Phase 7' };
  const start = m.index + m[0].length;
  let end = src.length; const rest = src.slice(start); const nx = rest.match(new RegExp(`^#{1,${m[1].length}}\\s`, 'm')); if (nx) end = start + nx.index;
  let body = src.slice(start, end);
  const fresh = new Set(gaps.map(row)); const regenerated = new Set([...gaps.map((g) => cell(g.asset)), ...(opts.assets || []).map(cell)]);
  let removed = 0; body = body.split('\n').filter((l) => { const a = assetOf(l); if (a && regenerated.has(a) && !fresh.has(l)) { removed++; return false; } return true; }).join('\n');
  const rows = gaps.map(row).filter((r) => !body.includes(r));
  if (!rows.length) return { text: src.slice(0, start) + body + src.slice(end), added: 0, removed, skipped: gaps.length, created: false };
  let created = false;
  if (body.includes(HEADER)) {
    // append after the last table row of the register
    const lines = body.split('\n'); let last = -1;
    for (let i = 0; i < lines.length; i++) if (/^\|/.test(lines[i])) last = i;
    lines.splice(last + 1, 0, ...rows); body = lines.join('\n');
  } else if (NOGAPS.test(body)) {
    body = body.replace(NOGAPS, [HEADER, SEP, ...rows].join('\n')); created = true;
  } else {
    // a § 11 with prose but no table yet: the register goes after the prose, before the footer separator
    const cut = body.search(/\n---\s*\n|\n\*Generated by/); const at = cut >= 0 ? cut : body.length;
    body = body.slice(0, at).replace(/\s+$/, '') + '\n\n' + [HEADER, SEP, ...rows].join('\n') + '\n' + body.slice(at); created = true;
  }
  return { text: src.slice(0, start) + body + src.slice(end), added: rows.length, removed, skipped: gaps.length - rows.length, created };
}

module.exports = { merge, row, HEADER };

if (require.main === module) {
  const args = process.argv.slice(2), files = args.filter((a) => !a.startsWith('--'));
  if (files.length < 2) { console.error('Usage: bun kit-gaps-merge.js <component.md> <asset-gaps.json> [--dry-run] [--json]'); process.exit(2); }
  const [comp, gapsFile] = files;
  let gaps, assets = []; try { const j = JSON.parse(fs.readFileSync(gapsFile, "utf8").replace(/\r\n?/g, "\n")); gaps = Array.isArray(j) ? j : j.gaps; assets = Array.isArray(j) ? [] : j.assets || []; } catch (e) { console.error('kit-gaps-merge: cannot read gaps — ' + e.message); process.exit(2); }
  if (!Array.isArray(gaps)) { console.error('kit-gaps-merge: the gaps file must be { "gaps": [ { asset, field, where, impact } ] }'); process.exit(2); }
  const src = fs.readFileSync(comp, "utf8").replace(/\r\n?/g, "\n");
  const r = merge(src, gaps, { assets });
  if (r.error) { console.error(`kit-gaps-merge: ${comp}: ${r.error}`); process.exit(1); }
  const changed = r.added > 0 || r.removed > 0;
  if (!args.includes('--dry-run') && changed) fs.writeFileSync(comp, r.text);
  const out = { file: comp, gaps: gaps.length, added: r.added, removed_stale: r.removed, skipped_present: r.skipped, table_created: r.created, written: !args.includes('--dry-run') && changed };
  console.log(args.includes('--json') ? JSON.stringify(out) : `kit-gaps-merge — ${comp}: ${r.added} row(s) added${r.removed ? `, ${r.removed} stale row(s) removed` : ''}${r.skipped ? `, ${r.skipped} already present` : ''}${r.created ? ' (register created)' : ''}${args.includes('--dry-run') ? ' — dry run, nothing written' : ''}`);
}
