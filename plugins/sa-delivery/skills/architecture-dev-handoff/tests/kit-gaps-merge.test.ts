/**
 * kit-gaps-merge.js — asset gaps into a Component Specification's § 11 register: one row per gap, the table
 * created in place of the "No gaps detected" line, a row already present never added twice, no anchor → refused.
 */
import { describe, test, expect, beforeAll, afterAll } from "bun:test";
import { mkdirSync, rmSync, writeFileSync, readFileSync } from "fs";
import { join } from "path";

// eslint-disable-next-line @typescript-eslint/no-var-requires
const { merge, HEADER } = require("../scripts/kit-gaps-merge.js");
const SCRIPT = join(__dirname, "..", "scripts", "kit-gaps-merge.js");
const TMP = join(__dirname, ".temp-kit-gaps-merge");

const head = "# Component Specification — Hub API\n\n<!-- managed by sa-skills:architecture-dev-handoff — do not edit manually -->\n<!-- TEMPLATE_VERSION: 4.3.1 -->\n\n## 10. Assets <!-- SECTION: Assets -->\n\n| Asset | File |\n|---|---|\n| OpenAPI | openapi.yaml |\n\n";
const tail = "\n\n---\n\n*Generated by `sa-skills:architecture-dev-handoff` on 2026-09-08*\n";
const withTable = head + "## 11. Open questions <!-- SECTION: Open Questions -->\n\nGaps detected during generation.\n\n" + HEADER + "\n|---------|-----------------|-----------------|----------------|\n| § Budgets | no latency analysis | run /sa-analysis:architecture-analysis latency-budget | no p99 to size against |" + tail;
const noGaps = head + "## 11. Open questions <!-- SECTION: Open Questions -->\n\nGaps detected during generation.\n\nNo gaps detected — all sections fully documented." + tail;
const gaps = [{ asset: "openapi.yaml", field: "securitySchemes", where: "docs/07-security-architecture.md § API auth", impact: "the contract has no auth scheme" }, { asset: "ddl.sql", field: "resource limits", where: "docs/09 § 11.1", impact: "HPA cannot be sized" }];

beforeAll(() => { rmSync(TMP, { recursive: true, force: true }); mkdirSync(TMP, { recursive: true }); });
afterAll(() => rmSync(TMP, { recursive: true, force: true }));

describe("kit-gaps-merge", () => {
  test("a regenerated asset's rows are replaced, not accumulated; other assets' rows and the specification's stay", () => {
    const first = merge(withTable, gaps).text;   // openapi.yaml + ddl.sql rows
    const closed = [{ asset: "openapi.yaml", field: "servers", where: "docs/components/x.md", impact: "no base URL" }];
    const r = merge(first, closed);
    expect(r).toMatchObject({ added: 1, removed: 1 });
    expect(r.text).not.toContain("| Assets — openapi.yaml | securitySchemes |");   // closed in the new run
    expect(r.text).toContain("| Assets — openapi.yaml | servers |");
    expect(r.text).toContain("| Assets — ddl.sql |");   // not regenerated this time
    expect(r.text).toContain("| § Budgets |");          // the specification's own row
    // an asset regenerated with no gap left clears its rows through `assets`
    const cleared = merge(r.text, [], { assets: ["openapi.yaml"] });
    expect(cleared).toMatchObject({ added: 0, removed: 1 });
    expect(cleared.text).not.toContain("| Assets — openapi.yaml |");
  });

  test("rows are appended to the existing register, after its last row and before the footer", () => {
    const r = merge(withTable, gaps);
    expect(r).toMatchObject({ added: 2, skipped: 0, created: false });
    expect(r.text).toMatch(/\| § Budgets \|[^\n]*\|\n\| Assets — openapi\.yaml \| securitySchemes \| docs\/07-security-architecture\.md § API auth \| the contract has no auth scheme \|\n\| Assets — ddl\.sql \| resource limits \| docs\/09 § 11\.1 \| HPA cannot be sized \|\n\n---\n/);
    expect(r.text.startsWith(head)).toBe(true);                                        // nothing above § 11 moves
  });

  test("with no gaps yet, the register is created in place of the 'No gaps detected' line", () => {
    const r = merge(noGaps, gaps.slice(0, 1));
    expect(r).toMatchObject({ added: 1, created: true });
    expect(r.text).not.toMatch(/No gaps detected/);
    expect(r.text).toMatch(new RegExp("Gaps detected during generation\\.\\n\\n" + HEADER.replace(/[|]/g, "\\|") + "\\n\\|[-|]+\\n\\| Assets — openapi\\.yaml \\|"));
  });

  test("a row already present is not added twice, so re-running is safe; a cell's pipe and newline are escaped", () => {
    const once = merge(withTable, gaps).text;
    const again = merge(once, gaps);
    expect(again).toMatchObject({ added: 0, skipped: 2 });
    expect(again.text).toBe(once);
    const r = merge(withTable, [{ asset: "ddl.sql", field: "col a|b", where: "line one\nline two", impact: "x" }]);
    expect(r.text).toMatch(/\| Assets — ddl\.sql \| col a\\\|b \| line one line two \| x \|/);
  });

  test("a file with no § 11 anchor is refused — the specification failed validation, and the CLI exits 1", () => {
    expect(merge(head + "## 11. Preguntas\n\nsin ancla\n", gaps).error).toMatch(/no `<!-- SECTION: Open Questions -->` heading/);
    writeFileSync(join(TMP, "bad.md"), head + "## 11. Preguntas\n\nsin ancla\n");
    writeFileSync(join(TMP, "gaps.json"), JSON.stringify({ gaps }));
    const r = Bun.spawnSync(["bun", SCRIPT, join(TMP, "bad.md"), join(TMP, "gaps.json")], { stdout: "pipe", stderr: "pipe" });
    expect(r.exitCode).toBe(1);
    expect(r.stderr.toString()).toMatch(/failed validation; log for Phase 7/);
  });

  test("the CLI writes the file, reports the count, and --dry-run writes nothing", () => {
    writeFileSync(join(TMP, "spec.md"), noGaps); writeFileSync(join(TMP, "gaps.json"), JSON.stringify({ gaps }));
    const dry = Bun.spawnSync(["bun", SCRIPT, join(TMP, "spec.md"), join(TMP, "gaps.json"), "--dry-run"], { stdout: "pipe", stderr: "pipe" });
    expect(dry.stdout.toString()).toMatch(/2 row\(s\) added \(register created\) — dry run, nothing written/);
    expect(readFileSync(join(TMP, "spec.md"), "utf-8")).toBe(noGaps);
    const r = Bun.spawnSync(["bun", SCRIPT, join(TMP, "spec.md"), join(TMP, "gaps.json"), "--json"], { stdout: "pipe", stderr: "pipe" });
    expect(JSON.parse(r.stdout.toString())).toMatchObject({ gaps: 2, added: 2, table_created: true, written: true });
    expect(readFileSync(join(TMP, "spec.md"), "utf-8")).toMatch(/\| Assets — ddl\.sql \|/);
  });
});
